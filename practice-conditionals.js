// Switch-case

let dayToday = prompt("What day is today ?");
switch (dayToday) {
    case "Monday":
        console.log("Today is Monday");
        break;
    case "Tuesday":
        console.log("Today is Tuesday");
        break;
    case "WED":
        console.log("Today is WED");
        break;
    case "Thurs":
        console.log("Today is Thurs");
        break;
    default:
        console.log("weekend days");
        break;
}
